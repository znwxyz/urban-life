/** 바닥에 닿는 납작한 그림자 */
const footShadow = (cx, g, rx, s) => E(cx, g - .3 * s, rx, Math.max(1, rx * .12), 'rgba(38,26,58,.18)');

/** 몸통 하나를 앞면 톤으로 오리고, 그 안쪽에만 볕 받는 면(lit)과 그늘 면(dark)을 덧댄다 */
function formed(x, g, s, body, p, lit, dark) {
  cut(x, g, s, body, p.mid);
  within(x, g, s, body, () => { if (lit) cut(x, g, s, lit, p.lit); if (dark) cut(x, g, s, dark, p.dark); });
}

/** 굵기가 있는 cm 선을 둥근 끝으로 긋는다 (다리·줄기·손잡이) */
function itemRod(x, g, s, pts, c, w) {
  ctx.strokeStyle = c; ctx.lineWidth = Math.max(.6, w * s); ctx.lineCap = 'round'; ctx.lineJoin = 'round';
  ctx.beginPath();
  pts.forEach((p, i) => {
    const X = (k) => x + p[k] * s, Y = (k) => g - p[k + 1] * s;
    if (!i) ctx.moveTo(X(0), Y(0));
    else if (p.length === 2) ctx.lineTo(X(0), Y(0));
    else ctx.quadraticCurveTo(X(0), Y(0), X(2), Y(2));
  });
  ctx.stroke();
}

/** a에서 b로 가는 방추형(잎·접은 우산)을 가운데 줄기로 나눈 두 쪽 cm 패스. bulge는 가장 굵은 곳의 위치(0~1) */
function spindleHalves(a, b, half, bulge = .45) {
  const dx = b[0] - a[0], dy = b[1] - a[1], len = Math.hypot(dx, dy) || 1, nx = -dy / len * half, ny = dx / len * half;
  const side = (k) => [a, [a[0] + dx * bulge * .5 + nx * k * 1.2, a[1] + dy * bulge * .5 + ny * k * 1.2, a[0] + dx * (bulge + .3) + nx * k, a[1] + dy * (bulge + .3) + ny * k, b[0], b[1]]];
  return { left: nx <= 0 ? side(1) : side(-1), right: nx <= 0 ? side(-1) : side(1) };
}

/** 잎 덩어리: 가장자리가 물결치는 오린 종이 세 장. 그늘(전체) 위에 왼쪽 위로 비킨 앞면, 그 위에 작은 볕 조각 (n은 물결 수) */
function leafMass(cx, cy, rx, ry, r, t, n = 7) {
  const lobes = Math.max(5, n + 2);
  const blob = (bx, by, brx, bry, salt) => {
    ctx.beginPath();
    for (let k = 0; k <= lobes; k++) {
      const a = (k / lobes) * TAU + r * 3 + salt, rr = .92 + hash(k % lobes, r * 17 + salt) * .12;
      const px = bx + Math.cos(a) * brx * rr, py = by + Math.sin(a) * bry * rr;
      if (!k) { ctx.moveTo(px, py); continue; }
      const am = a - Math.PI / lobes, bulge = 1.16 + hash(k % lobes, r * 29 + salt) * .1;
      ctx.quadraticCurveTo(bx + Math.cos(am) * brx * bulge, by + Math.sin(am) * bry * bulge, px, py);
    }
    ctx.closePath();
  };
  blob(cx, cy, rx, ry, 0); ctx.fillStyle = t(LEAF[3]); ctx.fill();
  ctx.save(); blob(cx, cy, rx, ry, 0); ctx.clip();
  blob(cx - rx * .12, cy - ry * .14, rx * .86, ry * .8, 1.3); ctx.fillStyle = t(LEAF[0]); ctx.fill();
  blob(cx - rx * .36, cy - ry * .42, rx * .42, ry * .34, 2.1); ctx.fillStyle = t(LEAF[2]); ctx.fill();
  ctx.restore();
}

/** 위에서 본 테두리(입구): 밝은 테 렌즈와 그 안의 어두운 속. cx 가운데, y 높이, rx 반폭, ry 깊이 */
function rimLens(x, g, s, cx, y, rx, ry, rimC, innerC, lip = .1) {
  cut(x, g, s, [[cx - rx, y], [cx, y + ry * 2, cx + rx, y], [cx, y - ry * 2, cx - rx, y]], rimC);
  const ix = rx * (1 - lip);
  cut(x, g, s, [[cx - ix, y + ry * .1], [cx, y + ry * 1.8, cx + ix, y + ry * .1], [cx, y - ry * .9, cx - ix, y + ry * .1]], innerC);
}

