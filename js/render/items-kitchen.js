function shelfBox(x, g, s, x0, y0, w, h, p) {
  cut(x, g, s, [[x0 + w, y0], [x0 + w + 3, y0 + 2], [x0 + w + 3, y0 + h + 2], [x0 + w, y0 + h]], p.dark);
  cut(x, g, s, [[x0, y0 + h], [x0 + w, y0 + h], [x0 + w + 3, y0 + h + 2], [x0 + 3, y0 + h + 2]], p.lit);
  cut(x, g, s, [[x0, y0], [x0 + w, y0], [x0 + w, y0 + h], [x0, y0 + h]], p.mid);
}

